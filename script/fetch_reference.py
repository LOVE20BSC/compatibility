#!/usr/bin/env python3
"""Fetch the published Uniswap V2 build artefacts and emit them as a Solidity fixture.

The local baseline cannot be produced by compiling the sources: `UniswapV2Library.pairFor` hard-codes
the CREATE2 init code hash of the published pair template, so a router compiled against any other build
looks for pools at addresses that were never created. Using the published `build/*.json` bytecode keeps
factory, pair and router consistent with each other, which is exactly what the compatibility baseline
is supposed to be: the canonical Uniswap V2 deployment, not our recompilation of it.
"""

import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "fixtures" / "ReferenceCode.sol"

SOURCES = {
    "FACTORY": "https://unpkg.com/@uniswap/v2-core@1.0.1/build/UniswapV2Factory.json",
    "PAIR": "https://unpkg.com/@uniswap/v2-core@1.0.1/build/UniswapV2Pair.json",
    "ROUTER": "https://unpkg.com/@uniswap/v2-periphery@1.1.0-beta.0/build/UniswapV2Router02.json",
}


def fetch(url: str) -> dict:
    with urllib.request.urlopen(url, timeout=30) as response:
        return json.loads(response.read())


def main() -> None:
    lines = [
        "// SPDX-License-Identifier: GPL-3.0",
        "// This file is generated by script/fetch_reference.py: do not edit by hand.",
        "//",
        "// Creation bytecode of the published Uniswap V2 build artefacts, used only to stand up the",
        "// local `anvil` baseline. Nothing in the business repositories imports this.",
        "pragma solidity =0.8.37;",
        "",
        "library ReferenceCode {",
    ]
    for name, url in SOURCES.items():
        data = fetch(url)
        bytecode = data["bytecode"].lower().removeprefix("0x")
        lines.append(f'    // {url}')
        lines.append(f'    // deployedBytecode sha256 of the published build is recorded in results/anvil')
        lines.append(f'    string internal constant {name}_SOURCE = "{url}";')
        lines.append(f'    bytes internal constant {name}_INIT = hex"{bytecode}";')
        lines.append("")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
